"""Writes lib/initials.ts: evenly spaced points around the outlines of "BC"
in STIX Two Text, the font of the name at the top of the page. The Fourier
drawing in the Contact section (components/FourierInitials.tsx) traces them.

Run from the repo root after changing TEXT or SAMPLES:
    pip install fonttools
    python scripts/trace-initials.py
"""

import math

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

FONT = "assets/fonts/STIXTwoText-Regular.ttf"
TEXT = "BC"
SAMPLES = 1024
HEIGHT = 200  # output units: the letters' height
OUT = "lib/initials.ts"


class Flatten(BasePen):
    """Turns a glyph's curves into polylines, one list of points per contour."""

    def __init__(self, glyph_set, dx):
        super().__init__(glyph_set)
        self.dx = dx
        self.contours = []

    def _add(self, p):
        self.contours[-1].append((p[0] + self.dx, -p[1]))  # SVG's y points down

    def _moveTo(self, p):
        self.contours.append([])
        self._add(p)

    def _lineTo(self, p):
        self._add(p)

    def _qCurveToOne(self, p1, p2):
        p0 = self._getCurrentPoint()
        for i in range(1, 13):
            t = i / 12
            u = 1 - t
            self._add((u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0],
                       u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1]))

    def _curveToOne(self, p1, p2, p3):
        p0 = self._getCurrentPoint()
        for i in range(1, 17):
            t = i / 16
            u = 1 - t
            self._add(tuple(u**3 * a + 3 * u * u * t * b + 3 * u * t * t * c + t**3 * d
                            for a, b, c, d in zip(p0, p1, p2, p3)))

    def _closePath(self):
        first = self.contours[-1][0]
        if self.contours[-1][-1] != first:
            self.contours[-1].append(first)


font = TTFont(FONT)
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
contours = []
dx = 0
for char in TEXT:
    name = cmap[ord(char)]
    pen = Flatten(glyph_set, dx)
    glyph_set[name].draw(pen)
    contours += pen.contours
    dx += glyph_set[name].width

# Start each contour at the point nearest where the last one ended, so the
# pen's jumps between contours are short.
for i in range(1, len(contours)):
    end = contours[i - 1][-1]
    ring = contours[i][:-1]
    k = min(range(len(ring)), key=lambda j: math.dist(ring[j], end))
    contours[i] = ring[k:] + ring[:k] + [ring[k]]

# One closed path through every contour. The straight jumps between contours
# (and back to the start) are pen-up: traced but not drawn.
segments = []  # (start, end, pen_up)
for i, contour in enumerate(contours):
    segments += [(a, b, False) for a, b in zip(contour, contour[1:])]
    following = contours[(i + 1) % len(contours)][0]
    segments.append((contour[-1], following, True))

lengths = [math.dist(a, b) for a, b, _ in segments]
total = sum(lengths)
points, pen_up = [], []
s, along = 0, 0.0
for n in range(SAMPLES):
    target = n * total / SAMPLES
    while along + lengths[s] < target:
        along += lengths[s]
        s += 1
    a, b, up = segments[s]
    t = (target - along) / lengths[s] if lengths[s] else 0
    points.append((a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])))
    pen_up.append(up)

# Center on the origin and scale to HEIGHT.
xs = [p[0] for p in points]
ys = [p[1] for p in points]
scale = HEIGHT / (max(ys) - min(ys))
cx = (max(xs) + min(xs)) / 2
cy = (max(ys) + min(ys)) / 2
flat = []
for x, y in points:
    flat += [round((x - cx) * scale, 1), round((y - cy) * scale, 1)]

# Pen-up stretches as [first, last] sample indexes.
gaps = []
for n, up in enumerate(pen_up):
    if up and (n == 0 or not pen_up[n - 1]):
        gaps.append([n, n])
    if up:
        gaps[-1][1] = n

width = round((max(xs) - min(xs)) * scale, 1)


def numbers(values):
    return ",".join(f"{v:g}" for v in values)


with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"""// Generated by scripts/trace-initials.py; edit that and rerun it instead.
// {SAMPLES} evenly spaced points around the outlines of "{TEXT}" in STIX Two
// Text, centered on the origin, {HEIGHT} units tall and {width} wide. `penUp`
// lists the [first, last] samples on the jumps between outlines.
export const initials = {{
  width: {width},
  height: {HEIGHT},
  points: [{numbers(flat)}],
  penUp: {gaps},
}};
""")

print(f"{len(contours)} outlines, {SAMPLES} samples, {len(gaps)} pen-up gaps -> {OUT}")
